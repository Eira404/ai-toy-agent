/** 阶段二·组内整合：把一组候选整合成当前有效结论。 */
export const STAGE_2_CONSOLIDATION_SYSTEM_MESSAGE = `
对输入的一组候选记忆进行整合，消除重复信息，合并互补信息，处理纠错、状态变化及事实冲突，形成准确、完整的当前有效记忆。

**整合规则：**

1. **重复信息**：识别并合并表达相同事实的候选，避免重复保留，同时不能丢失各候选中独有的有效信息。
2. **补充信息**：对于主体、对象和主题相同，且内容相互兼容的候选，合并其有效信息，补全事实细节及必要上下文，不遗漏有价值的具体信息。
3. **明确纠错**：当候选明确表明之前的信息有误或已被更正时，以更正后的信息为准，只保留正确结论，不将已纠正的错误信息作为有效记忆保留。
4. **状态变化**：当候选反映同一事实在不同时期发生变化时，以当前有效状态为主。历史状态仅在有助于理解变化过程或具有独立记忆价值时保留，并明确区分时间和状态，不能将正常变化误判为事实冲突。
5. **未解释的冲突**：当候选之间存在无法通过纠错或状态变化解释的事实冲突时，以较新的候选作为当前记忆结论，不推断冲突产生的原因，不擅自调和或编造解释。较旧的信息不再作为当前有效结论保留。
6. **无关信息**：如果候选实际涉及不同的对象、事件或主题，且不存在明确的关联关系，则分别整合、独立输出，不强行合并成同一条记忆。

**通用要求：**

- 以候选提供的事实为唯一依据，不凭空补充人物、时间、地点、关系、原因、结果等信息。
- 保留重要的主体、对象、时间、地点、数值、条件、关系及状态信息，不因追求简洁而丢失关键事实。
- 消除重复和冗余表达，但不改变原始事实的含义。
- 明确区分已确认事实、历史事实和当前状态，不将计划、推测或不确定信息改写为确定事实。
- 当无法判断候选之间的关系或新旧顺序时，不擅自作出判断，保留必要的不确定性。

**输出要求：**

输出整合后的记忆内容。存在多个互不相关的主题时，分别输出多个独立结果。不输出整合过程和额外解释。

你会在<CANDIDATES></CANDIDATES>中收到需要整合的候选。
`.trim()

export function buildGroupingUserMessage(candidates: string): string {
  return `<CANDIDATES>\n${candidates}\n</CANDIDATES>`
}

