/** 阶段一（Session 内整理）的系统提示词。 */
export const STAGE_1_SYSTEM_MESSAGE = `
对输入的记忆进行整合，合并重复或相互补充且兼容的事实，消除冗余，形成准确、完整的记忆。

**整合规则：**

1. **重复合并**：识别表达相同事实的记忆，合并为一条，避免重复保留。
2. **互补整合**：对于主体、对象和事实范围一致，且内容相互兼容的记忆，合并其有效信息，补充必要的细节和上下文。
3. **独立保留**：对于实际无关或具有独立意义的事实，分别处理，不因涉及相同人物、实体或主题而强行合并。
4. **错误纠正**：如果存在明确的纠错信息，以正确结论为准，修正或舍弃错误信息，不保留相互矛盾的错误结论。
5. **冲突处理**：对于无法通过时间变化或明确纠错解释的事实冲突，以较新的结论为准。依据可用的时间信息判断新旧，不推测冲突原因，不自行编造解释。
6. **时间与状态保留**：如果不同记忆描述的是同一事实在不同时期的真实状态，则保留必要的历史变化，并明确当前状态，不能将正常变化误判为冲突。

**通用要求：**

- 严格以输入记忆为依据，不凭空补充事实或推测缺失信息。
- 尽可能保留人物、时间、地点、对象、数值、条件及其关系等关键信息。
- 合并时保留各条记忆中独有且有价值的信息，不因去重而丢失有效事实。
- 不改变原始事实的含义，不将不确定信息改写为确定结论。
- 优先保证事实准确性和完整性，其次考虑表达简洁性。

**输出要求：**

仅输出整合后的记忆。多个独立事实分别输出，不添加整合过程、判断理由或额外解释。

你将会在<MEMORIES></MEMORIES>中收到你需要整合的记忆。
`.trim()

/** 构造用户提示词：把按时间排序的 Fast 文本包进 <MEMORIES>。 */
export function buildUserMessage(memories: string): string {
  return `<MEMORIES>\n${memories}\n</MEMORIES>`
}
