import { RelationalError, type RelationalSchemaDefinition } from "toy-storage-relational"
import type { PoolClient } from "pg"
import { columnSql, qualifiedTable, quoteIdentifier } from "./sql.js"

/**
 * 启动时只创建缺失的结构；已有表的结构演进仍需显式迁移。
 *
 * @param client 同一事务中的 PostgreSQL 连接。
 * @param schemaName PostgreSQL schema 名称。
 * @param schema 已校验的逻辑 Schema。
 * @returns 所有 DDL 成功后完成的 Promise。
 */
export async function createMissingSchema(
  client: PoolClient,
  schemaName: string,
  schema: RelationalSchemaDefinition,
): Promise<void> {
  await client.query(`CREATE SCHEMA IF NOT EXISTS ${quoteIdentifier(schemaName)}`)
  for (const [tableName, table] of Object.entries(schema.tables)) {
    const columns = Object.entries(table.columns).map(([name, column]) => {
      if (column.generated && (name !== table.primaryKey || column.type !== "integer")) {
        throw new RelationalError(
          "invalid-schema",
          `仅支持 integer 主键自动生成：${tableName}.${name}`,
        )
      }
      const generated = column.generated ? " GENERATED BY DEFAULT AS IDENTITY" : ""
      const nullable = column.nullable ? "" : " NOT NULL"
      return `${quoteIdentifier(name)} ${columnSql(column)}${generated}${nullable}`
    })
    const primary = `PRIMARY KEY (${quoteIdentifier(table.primaryKey)})`
    await client.query(
      `CREATE TABLE IF NOT EXISTS ${qualifiedTable(schemaName, tableName)} (${[...columns, primary].join(", ")})`,
    )

    for (const index of table.indexes ?? []) {
      // PostgreSQL 的 index 名在 schema 范围内唯一，加入表名前缀避免不同表同名。
      const physicalName = `${tableName}_${index.name}`
      if (Buffer.byteLength(physicalName, "utf8") > 63) {
        throw new RelationalError("invalid-schema", `索引名 '${physicalName}' 超过 PostgreSQL 限制`)
      }
      const unique = index.unique ? "UNIQUE " : ""
      await client.query(
        `CREATE ${unique}INDEX IF NOT EXISTS ${quoteIdentifier(physicalName)} ON ${qualifiedTable(schemaName, tableName)} (${index.fields.map(quoteIdentifier).join(", ")})`,
      )
    }
  }
}
