import type {
  RelationalColumnDefinition,
  RelationalIndexDefinition,
  RelationalSchemaDefinition,
  RelationalTableDefinition,
} from "toy-storage-relational"
import { MigrateError } from "./error.js"
import { columnSql, qualifiedTable, quoteIdentifier } from "./sql.js"
import type { DiffAction } from "./types.js"

/** 把一个 diff action 展开成要执行的 SQL 语句列表（可能多条，如回填三段）。 */
export function actionSqls(
  schemaName: string,
  desired: RelationalSchemaDefinition,
  action: DiffAction,
): readonly string[] {
  switch (action.kind) {
    case "createTable": {
      const table = requireTable(desired, action.table)
      return [createTableSql(schemaName, action.table, table)]
    }
    case "addColumn": {
      const table = requireTable(desired, action.table)
      const column = table.columns[action.column]
      if (column === undefined) {
        throw new MigrateError("invalid-schema", `找不到列 '${action.table}.${action.column}'`)
      }
      return addColumnSql(schemaName, action.table, action.column, column)
    }
    case "createIndex": {
      const table = requireTable(desired, action.table)
      const index = (table.indexes ?? []).find((candidate) => candidate.name === action.index)
      if (index === undefined) {
        throw new MigrateError("invalid-schema", `找不到索引 '${action.table}.${action.index}'`)
      }
      return [createIndexSql(schemaName, action.table, index)]
    }
  }
}

function requireTable(desired: RelationalSchemaDefinition, tableName: string): RelationalTableDefinition {
  const table = desired.tables[tableName]
  if (table === undefined) {
    throw new MigrateError("invalid-schema", `找不到表 '${tableName}'`)
  }
  return table
}

function createTableSql(schemaName: string, tableName: string, table: RelationalTableDefinition): string {
  const columns = Object.entries(table.columns).map(([name, column]) => {
    const generated = column.generated ? " GENERATED BY DEFAULT AS IDENTITY" : ""
    const nullable = column.nullable === true ? "" : " NOT NULL"
    const defaultValue = column.default !== undefined ? ` DEFAULT ${column.default}` : ""
    return `${quoteIdentifier(name)} ${columnSql(column)}${generated}${nullable}${defaultValue}`
  })
  const primary = `PRIMARY KEY (${quoteIdentifier(table.primaryKey)})`
  return `CREATE TABLE IF NOT EXISTS ${qualifiedTable(schemaName, tableName)} (${[...columns, primary].join(", ")})`
}

/**
 * 加列：
 * - 有 `backfill`：先加可空列 → 回填 → （非空则）SET NOT NULL；
 * - 无 `backfill` 但有 `default`：ADD COLUMN ... DEFAULT；
 * - 都没有：ADD COLUMN（非空且无回填的情况由 diff 阶段拦截）。
 */
function addColumnSql(
  schemaName: string,
  tableName: string,
  columnName: string,
  column: RelationalColumnDefinition,
): readonly string[] {
  const tableQ = qualifiedTable(schemaName, tableName)
  const columnQ = quoteIdentifier(columnName)
  const type = columnSql(column)

  if (column.backfill !== undefined) {
    const statements = [
      `ALTER TABLE ${tableQ} ADD COLUMN ${columnQ} ${type}`,
      `UPDATE ${tableQ} SET ${columnQ} = ${column.backfill}`,
    ]
    if (column.nullable !== true) {
      statements.push(`ALTER TABLE ${tableQ} ALTER COLUMN ${columnQ} SET NOT NULL`)
    }
    return statements
  }

  const defaultValue = column.default !== undefined ? ` DEFAULT ${column.default}` : ""
  const notNull = column.nullable === true ? "" : " NOT NULL"
  return [`ALTER TABLE ${tableQ} ADD COLUMN ${columnQ} ${type}${defaultValue}${notNull}`]
}

function createIndexSql(schemaName: string, tableName: string, index: RelationalIndexDefinition): string {
  const physicalName = `${tableName}_${index.name}`
  const unique = index.unique === true ? "UNIQUE " : ""
  const fields = index.fields.map(quoteIdentifier).join(", ")
  return `CREATE ${unique}INDEX IF NOT EXISTS ${quoteIdentifier(physicalName)} ON ${qualifiedTable(schemaName, tableName)} (${fields})`
}
